-- Create a secure relational ledger table to hold incoming transaction events
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference TEXT UNIQUE NOT NULL,
    amount BIGINT NOT NULL,
    email TEXT NOT NULL,
    status TEXT NOT NULL,
    processed_at TIMESTAMPTZ DEFAULT NOW()
);

-- Turn on row level security protections to wall off direct public alterations
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

-- Explicitly map access grants down to the anonymous data API layer
GRANT ALL ON public.transactions TO postgres, service_role;
GRANT INSERT ON public.transactions TO anon, authenticated;

-- Provision an unrestricted webhook policy to handle real-time insert streams safely
CREATE POLICY "Allow anonymous webhooks to insert transaction records" 
ON public.transactions 
FOR INSERT 
WITH CHECK (true);
